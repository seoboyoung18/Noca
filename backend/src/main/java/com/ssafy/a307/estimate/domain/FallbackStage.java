package com.ssafy.a307.estimate.domain;

/**
 * 유사 사례를 찾을 때 조건을 어디까지 넓혔는지.
 *
 * <p>검색은 {@code repair_case.model_id} 로 동일 차량명부터 시작해 사례가 모자라면 비슷한
 * 수리비대, 그래도 모자라면 전체로 물러난다. <b>어느 단계까지 물러났는지를 화면에 표시하는 것이 필수다</b>
 * — "동일 차종 37건 기준"과 "전체 사례 37건 기준"은 사용자가 견적을 믿을지 판단하는 근거가
 * 전혀 다르다.
 *
 * <p><b>단계는 신뢰도 등급과 짝을 이룬다.</b> {@link com.ssafy.a307.estimate.entity.ConfidenceGrade}
 * 가 이미 같은 구분을 등급 쪽에서 설명하고 있다 — 완화 없음이 HIGH, 한 단계가 MEDIUM,
 * 전체까지가 LOW 다. 둘을 한 자리에 합치지 않은 것은 등급이 사례 건수도 함께 보기 때문이다.
 *
 * <p><b>선언 순서가 곧 "얼마나 넓혔나" 다.</b> {@link LowConfidenceRule} 이 {@code ordinal} 로
 * "이 단계 이상 넓혔는가" 를 판정한다(S15P21A307-291). 값을 중간에 끼워 넣으면 그 판정이
 * 조용히 바뀐다 — 새 단계는 넓어지는 방향의 제자리에 넣어야 한다.
 *
 * <p><b>사고 스냅샷이 항상 있으므로 1단계는 언제나 시도된다.</b> {@code accident.snapshot_model_id}
 * 가 {@code NOT NULL} 이라 "차량 정보가 없어 처음부터 넓게 찾았다"는 경우는 없다.
 */
public enum FallbackStage {

    /** 동일 차량명. 조건을 넓히지 않았다. */
    MODEL,

    /**
     * 비슷한 수리비대. 같은 차량명 사례가 모자라 한 단계 넓혔다.
     *
     * <p><b>차급이 아니라 실측 수리비 지수의 사분위다.</b> 차급(경·소·중·대)은 배기량과
     * 크기 기준이라 수리비를 설명하지 못한다 — 견적서 코퍼스 실측에서 소·중·대의 지수
     * 중앙값이 1.01 / 0.99 / 1.05 로 6% 안에 있었고 범위가 완전히 겹쳤다. 같은 차급으로
     * 좁혀도 비용이 비슷한 사례가 모이지 않았다는 뜻이다.
     * 근거: {@code Docs/Erd/A307_VEHICLE_AXIS.md}
     */
    PRICE_TIER,

    /**
     * 옛 차급 완화. <b>새로 만들어지지 않는다.</b> 2026-09-17 이전에 저장된
     * {@code estimate_item.ref_condition} 행을 읽기 위해서만 남아 있다 — 지우면 그 행들이
     * Jackson 역직렬화에서 터진다. 그때의 검색은 실제로 차급 기준이었으므로 근거 문구도
     * "동일 차급" 그대로 둔다.
     *
     * <p>자리는 {@link #PRICE_TIER} 와 {@link #ALL} 사이다. {@code ALL} 보다 앞에 두어야
     * {@code warn-from-stage=ALL} 설정에서 옛 행의 경고 여부가 그대로 유지된다.
     * 옛 행이 모두 정리되면 지워도 된다.
     */
    CAR_CLASS,

    /** 전체. 차량 조건을 모두 풀었다 — 가장 약한 근거다. */
    ALL
}
