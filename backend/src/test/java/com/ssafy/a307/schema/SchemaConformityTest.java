/**
 * 테스트 스키마({@code schema-h2.sql})가 정본({@code Docs/Erd/A307_ddl_final.sql})과 어긋나지 않는지
 * 본다. <b>prompt24 5장의 D-B(새 의존성 없는 정적 대조)</b> 구현이다.
 *
 * <p><b>왜 필요한가.</b> {@code schema-h2.sql} 은 손으로 유지하는 별도 사본이고, 테스트의
 * {@code ddl-auto=validate} 는 정본이 아니라 <b>그 사본</b>을 검증한다. 사본이 낡으면
 * "테스트 전부 통과" 가 "운영에서 기동됨" 을 더 이상 뜻하지 않는다. 실제로 그 사고가 일어났다 —
 * {@code estimate_validation.llm_summary} 가 정본 {@code TEXT} · H2 {@code CLOB} 이었고 엔티티의
 * {@code @Lob} 이 H2 하고만 맞아, 365개 테스트가 전부 통과하는 채로 PostgreSQL 기동만
 * {@code SchemaManagementException} 으로 죽었다(answer24 F-1).
 *
 * <p><b>무엇을 보장하는가.</b> H2 에 존재하는 테이블에 한해 컬럼·타입·NULL 여부·DEFAULT·CHECK·
 * UNIQUE·FK 정의가 정본과 <b>글자 단위로</b> 같아야 한다. 다른 것이 허용되는 경우는
 * {@link #H2_SUBSTITUTIONS} 에 적힌 H2 미지원 치환뿐이고, 그 목록은 파일 머리말에도 같이 적혀
 * 있어야 한다({@link Header}). 치환을 늘리려면 두 곳을 함께 고쳐야 하므로 조용히 늘어나지 않는다.
 *
 * <p><b>무엇을 보장하지 않는가.</b> 정본에 있고 H2 에 없는 테이블은 실패시키지 않는다 — 아직
 * 엔티티도 소비자도 없는 도메인이라 옮길 이유가 없다. 대신 그 목록을 고정해 두어
 * <b>새 누락이 생기면 깨진다</b>({@link Coverage}). JPA ↔ H2 일치는 이 테스트가 보지 않는다.
 * {@code ddl-auto=validate} 가 컨텍스트 기동 시점에 검증하므로 매핑이 어긋나면
 * {@code @SpringBootTest} 가 통째로 뜨지 않는다 — 셋 중 둘을 여기서, 나머지 하나를 기동으로 본다.
 */
