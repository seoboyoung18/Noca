    private record Substitution(String canonicalToken, String h2Token, String description) {

        String apply(String sql) {
            return sql.replaceAll("\\b" + Pattern.quote(canonicalToken) + "\\b",
                    Matcher.quoteReplacement(h2Token));
        }
    }

    static Stream<String> sharedTables() {
        return sharedTableNames().stream();
    }

    private static List<String> sharedTableNames() {
        List<String> shared = new ArrayList<>(canonical().keySet());
        shared.retainAll(h2().keySet());
        return shared;
    }

    /** 정본을 H2 표기로 치환한 뒤 파싱한 결과. */
    private static Map<String, List<String>> canonical() {
        String sql = normalize(rawCanonical());
        for (Substitution substitution : H2_SUBSTITUTIONS) {
            sql = substitution.apply(sql);
        }
        return parse(sql);
    }

    /** 치환 없이 파싱한 정본. 치환 자체가 맞는지 볼 때만 쓴다. */
    private static Map<String, List<String>> canonicalWithoutSubstitution() {
        return parse(normalize(rawCanonical()));
    }

    private static Map<String, List<String>> h2() {
        return parse(normalize(rawH2()));
    }

    /**
     * {@code CREATE TABLE ... ( ... );} 을 테이블별 정의 목록으로 나눈다.
     * 괄호 깊이를 세므로 {@code NUMERIC(7,2)} 나 CHECK 안의 쉼표에 걸리지 않는다.
     */
    private static Map<String, List<String>> parse(String sql) {
        Map<String, List<String>> tables = new LinkedHashMap<>();
        Matcher matcher = Pattern.compile("CREATE TABLE (\\w+) \\(").matcher(sql);
        while (matcher.find()) {
            int start = matcher.end();
            int end = closingParen(sql, start);
            tables.put(matcher.group(1), split(sql.substring(start, end)));
        }
        return tables;
    }

    private static int closingParen(String sql, int start) {
        int depth = 1;
        for (int i = start; i < sql.length(); i++) {
            char c = sql.charAt(i);
            if (c == '(') depth++;
            if (c == ')' && --depth == 0) return i;
        }
        throw new IllegalStateException("CREATE TABLE 의 괄호가 닫히지 않았다");
    }

    private static List<String> split(String body) {
        List<String> definitions = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        int depth = 0;
        for (char c : body.toCharArray()) {
            if (c == '(') depth++;
            if (c == ')') depth--;
            if (c == ',' && depth == 0) {
                addTo(definitions, current);
                continue;
            }
            current.append(c);
        }
        addTo(definitions, current);
        return definitions;
    }

    private static void addTo(List<String> definitions, StringBuilder current) {
        String value = current.toString().strip();
        if (!value.isEmpty()) definitions.add(value);
        current.setLength(0);
    }

    /** 한 컬럼의 타입·제약 부분(컬럼명 제외). */
    private static String definition(Map<String, List<String>> tables, String table, String column) {
        return tables.getOrDefault(table, List.of()).stream()
                .filter(definition -> definition.equals(column) || definition.startsWith(column + " "))
                .map(definition -> definition.substring(column.length()).strip())
                .findFirst()
                .orElseThrow(() -> new AssertionError(table + "." + column + " 을 찾지 못했다"));
    }

    private static Set<String> constraintNames(List<String> definitions, String keyword) {
        Set<String> names = new TreeSet<>();
        for (String definition : definitions) {
            Matcher matcher = Pattern.compile("^CONSTRAINT (\\w+) " + keyword + "\\b").matcher(definition);
            if (matcher.find()) names.add(matcher.group(1));
        }
        return names;
    }

    private static Set<String> indexNames(String sql) {
        Set<String> names = new TreeSet<>();
        Matcher matcher = Pattern.compile("CREATE INDEX (\\w+)").matcher(normalize(sql));
        while (matcher.find()) names.add(matcher.group(1));
        return names;
    }

    /** 주석 제거 · 공백 한 칸 정리 · 대문자화. 표기 치환은 여기서 하지 않는다. */
    private static String normalize(String sql) {
        return stripComments(sql)
                .replaceAll("\\s+", " ")
                .toUpperCase(Locale.ROOT)
                .replaceAll("\\s*\\(\\s*", " (")
                .replaceAll("\\s*\\)\\s*", ") ")
                .replaceAll("\\s+", " ")
                .replaceAll("\\s*,\\s*", ", ");
    }

    private static String stripComments(String sql) {
        return sql.replaceAll("--[^\\n]*", " ");
    }

    /** 첫 {@code CREATE}/{@code DROP} 이전까지가 머리말이다. */
    private static String header(String sql) {
        Matcher matcher = Pattern.compile("(?m)^\\s*(CREATE|DROP)\\b").matcher(sql);
        return matcher.find() ? sql.substring(0, matcher.start()) : sql;
    }

    private static String rawCanonical() {
        return read(repoFile("Docs/Erd/A307_ddl_final.sql"));
    }

    private static String rawH2() {
        Path fromModule = Path.of("src/test/resources/schema-h2.sql");
        return read(Files.exists(fromModule) ? fromModule : Path.of("backend").resolve(fromModule));
    }

    private static String read(Path path) {
        try {
            return Files.readString(path, StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("스키마 파일을 읽지 못했다: " + path, e);
        }
    }

    /** 테스트 작업 디렉터리가 {@code backend} 일 때와 저장소 루트일 때를 모두 지원한다. */
    private static Path repoFile(String relativePath) {
        Path fromModule = Path.of("..").resolve(relativePath);
        return Files.exists(fromModule) ? fromModule : Path.of(relativePath);
    }
