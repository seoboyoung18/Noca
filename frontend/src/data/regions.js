export const findRegion = (sido) => REGIONS.find((r) => r.sido === sido)

// 검색용 주소 문자열 후보 (새 명칭 → 이전 명칭 순)
export function regionAddresses(sido, gu) {
  const r = findRegion(sido)
  const names = [sido, r?.alt].filter(Boolean)
  return names.map((n) => [n, gu].filter(Boolean).join(' '))
}

// 칩·목록 제목에 쓰는 짧은 표시명: "역삼동" / "강남구" / "세종" / "수원시"
// dong: 읍·면·동(또는 시 아래 구) 표시명 — 선택한 경우 가장 구체적인 단위를 우선 표시
export function regionLabel(sido, gu, dong) {
  if (dong) return dong
  if (gu) return gu
  return findRegion(sido)?.short || sido
}
