-- S15P21A307-554 · 사고 이력 숨기기
--   accident.hidden_at
--
-- ⚠️ 이 저장소는 `spring.jpa.hibernate.ddl-auto=validate` 다.
--    **이 SQL 을 운영 DB 에 먼저 적용하지 않으면 애플리케이션이 기동하지 않는다.**
--    Accident 엔티티가 이 열을 매핑하기 때문이다.
--    배포 순서: (1) 이 파일 적용 → (2) 애플리케이션 배포
--
-- 왜 필요한가
--   사고 이력을 정리할 방법이 없었다. 화면의 "숨기기" 는 브라우저 localStorage 에만 남아
--   기기를 바꾸거나 캐시를 지우면 숨긴 것이 다시 나타난다. 서버는 그 사실을 모른다.
--
-- 왜 삭제가 아니라 숨김인가
--   사고를 지우면 사진·분석·견적·체크리스트가 CASCADE 로 함께 사라지고 되돌릴 수 없다.
--   사용자가 원한 것은 "목록에서 안 보이게" 였다. 숨김이면 목록을 만드는 두 쿼리만 거르면
--   되지만, 삭제라면 사고를 읽는 12개 서비스 26개 지점이 모두 대상이 된다 — 한 곳만
--   빠뜨려도 지운 사고가 그 경로로 다시 나타난다.
--
--   영구 삭제가 필요해지면 그때 별도로 연다. 숨김이 있다고 삭제를 못 하는 것은 아니다.
--
-- 왜 boolean 이 아니라 시각인가
--   vehicle.deleted_at 과 같은 방식이다. 언제 숨겼는지가 남으면 "언제부터 안 보였나" 에
--   답할 수 있다. boolean 은 그 질문에 답하지 못하고, 나중에 알고 싶어지면 다시
--   마이그레이션해야 한다.
--
-- 인덱스를 만들지 않는 이유
--   목록 조회는 이미 소유자(vehicle.member_id)로 좁혀진 뒤 이 열을 본다. 한 사람의 사고
--   수가 인덱스가 필요할 규모가 아니다. 측정 없이 인덱스를 먼저 만들지 않는다.

ALTER TABLE accident ADD COLUMN hidden_at TIMESTAMPTZ;
